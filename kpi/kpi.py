"""Progress KPI with explicit denominators. Levels are computed from evidence, not self-reported.

Run from the repo root:  python -m kpi.kpi [--write]
"""
import io
import json
import sys
import unittest
from pathlib import Path

ROOT = Path(__file__).resolve().parents[1]
LEVELS = ["NONE", "SPECIFIED", "IMPLEMENTED", "TESTED", "INTEGRATED"]

def run_tests(ids):
    """Return {test_id: 'PASS'|'FAIL'|'ERROR'|'MISSING'}."""
    out = {}
    loader = unittest.TestLoader()
    for tid in sorted(set(ids)):
        try:
            suite = loader.loadTestsFromName(tid)
        except Exception:
            out[tid] = "MISSING"
            continue
        result = unittest.TextTestRunner(stream=io.StringIO(), verbosity=0).run(suite)
        if result.testsRun == 0 or any("_FailedTest" in str(t) for t, _ in result.errors):
            out[tid] = "MISSING"
        elif result.errors:
            out[tid] = "ERROR"
        elif result.failures:
            out[tid] = "FAIL"
        else:
            out[tid] = "PASS"
    return out

def read(path):
    p = ROOT / path
    return p.read_text(encoding="utf-8") if p.is_file() else ""

def evaluate(item, test_status):
    """Level k requires level k-1. Returns (level_name, missing_reasons, max_level_index)."""
    max_idx = 4 if item.get("integration") else 3  # INTEGRATED applies only where an evidence path is defined
    missing = []
    idx = 0
    doc = item.get("doc") or []
    if doc and doc[1] in read(doc[0]):
        idx = 1
    else:
        missing.append("doc anchor")
    if idx == 1:
        code = item.get("code") or []
        if code and all(sym in read(f) for f, sym in code):
            idx = 2
        else:
            missing.append("code symbol")
    if idx == 2:
        tests = item.get("tests") or []
        bad = [t for t in tests if test_status.get(t) != "PASS"]
        if tests and not bad:
            idx = 3
        else:
            missing.append("tests passing" + (f" ({len(bad)} not)" if bad else " (none listed)"))
    if idx == 3 and item.get("integration"):
        if read(item["integration"]).strip():
            idx = 4
        else:
            missing.append("integration evidence")
    return LEVELS[idx], missing, max_idx

def real_model_stats(scope, scenarios_count):
    target = scenarios_count * scope["target_trials_per_scenario"]
    runs = []
    for f in sorted((ROOT / "kpi" / "real_runs").glob("*.json")):
        runs.extend(json.loads(f.read_text(encoding="utf-8")))
    models = {}
    for r in runs:
        m = models.setdefault(r["model"], {"attempted": 0, "passed": 0})
        m["attempted"] += 1
        m["passed"] += 1 if r["passed"] else 0
    return target, models

def build():
    from kpi.real_eval import SCENARIOS
    scope = json.loads(read("kpi/scope.json"))
    items = scope["v0"] + scope["deferred"]
    status = run_tests([t for i in items for t in i.get("tests", [])])
    rows = []
    for group in ("v0", "deferred"):
        for it in scope[group]:
            level, missing, max_idx = evaluate(it, status)
            rows.append({"group": group, "id": it["id"], "title": it["title"], "level": level, "idx": LEVELS.index(level), "max": max_idx, "missing": missing})
    target, models = real_model_stats(scope, len(SCENARIOS))
    return scope, rows, status, target, models, len(SCENARIOS)

def pct(n, d):
    return f"{100 * n / d:.1f}%" if d else "n/a"

def report(scope, rows, status, target, models, n_scen):
    v0 = [r for r in rows if r["group"] == "v0"]
    def prog(rs):
        return sum(r["idx"] for r in rs), sum(r["max"] for r in rs)
    p_v0, d_v0 = prog(v0)
    p_all, d_all = prog(rows)
    L = ["# Progress KPI (generated by `python -m kpi.kpi --write`; do not edit)\n"]
    L.append(f"Evidence tests executed: {len(status)}; passing: {sum(v == 'PASS' for v in status.values())}.\n")
    L.append("## 1. Headline progress\n")
    L.append("| KPI | Numerator | Denominator | Rate |\n| --- | --- | --- | --- |")
    L.append(f"| v0 progress (level points) | {p_v0} | {d_v0} = sum of each v0 item's max level ({len(v0)} items; max 3, or 4 where an integration evidence path is defined) | **{pct(p_v0, d_v0)}** |")
    L.append(f"| Full scope (v0 + deferred) | {p_all} | {d_all} | {pct(p_all, d_all)} |")
    for lv in LEVELS[1:]:
        k = LEVELS.index(lv)
        applicable = [r for r in v0 if r["max"] >= k]
        reached = sum(r["idx"] >= k for r in applicable)
        L.append(f"| v0 items reaching {lv} | {reached} | {len(applicable)} items | {pct(reached, len(applicable))} |")
    L.append("\n**Read the headline together with the INTEGRATED row**: TESTED means scripted mock models and a virtual project pass. It is not evidence that a real model or the real chat app works.")
    L.append("\nLevel points: NONE 0, SPECIFIED 1, IMPLEMENTED 2, TESTED 3, INTEGRATED 4. A level counts only if every lower level holds. TESTED = all listed tests pass in this run. INTEGRATED = non-empty evidence file from a real host/model run.\n")
    L.append("## 2. Real-model KPI (separate; scripted mocks never count)\n")
    L.append(f"Denominator per model = {n_scen} scenarios x {scope['target_trials_per_scenario']} trials = **{target}** runs.\n")
    if not models:
        L.append("**Not measured**: no run files in `kpi/real_runs/`. Success rate is undefined, not 0%.\n")
    else:
        L.append("| Model | Coverage (attempted / target) | Success (passed / attempted) |\n| --- | --- | --- |")
        for m, s in sorted(models.items()):
            L.append(f"| {m} | {s['attempted']} / {target} = {pct(s['attempted'], target)} | {s['passed']} / {s['attempted']} = {pct(s['passed'], s['attempted'])} |")
        L.append("")
    L.append("## 3. Items\n")
    L.append("| ID | Item | Level | Max | Missing for next level |\n| --- | --- | --- | --- | --- |")
    for r in rows:
        L.append(f"| {r['id']} | {r['title']} | {r['level']} | {LEVELS[r['max']]} | {', '.join(r['missing']) or '-'} |")
    bad = sorted(t for t, v in status.items() if v != "PASS")
    if bad:
        L.append("\n## 4. Evidence tests not passing\n")
        L.extend(f"- {t}: {status[t]}" for t in bad)
    return "\n".join(L) + "\n"

def main():
    sys.path.insert(0, str(ROOT))
    text = report(*build())
    if "--write" in sys.argv:
        (ROOT / "kpi" / "REPORT.md").write_text(text, encoding="utf-8")
    sys.stdout.buffer.write(text.encode("utf-8"))

if __name__ == "__main__":
    main()
